-- Slice 5A.2: expansión compatible. El saldo autoritativo sigue siendo
-- insumo.stock_actual; no se infieren unidades ni se crean movimientos.
ALTER TABLE public.insumo
    ADD COLUMN unidad_base_familia varchar(8),
    ADD COLUMN unidad_base_codigo varchar(8),
    ADD COLUMN estado_inventario_5a varchar(16) NOT NULL DEFAULT 'PENDIENTE',
    ADD COLUMN reconciliacion_actual_id bigint;

ALTER TABLE public.insumo
    ADD CONSTRAINT insumo_unidad_base_par_check CHECK (
        (unidad_base_familia IS NULL AND unidad_base_codigo IS NULL)
        OR (unidad_base_familia IS NOT NULL AND unidad_base_codigo IS NOT NULL AND (
            (unidad_base_familia = 'MASS' AND unidad_base_codigo = 'g')
            OR (unidad_base_familia = 'VOLUME' AND unidad_base_codigo = 'ml')
            OR (unidad_base_familia = 'COUNT' AND unidad_base_codigo = 'unidad')
        ))
    ),
    ADD CONSTRAINT insumo_estado_inventario_5a_check CHECK (
        estado_inventario_5a IN ('PENDIENTE', 'RECONCILIADO', 'ACTIVO_5A')
    ),
    ADD CONSTRAINT insumo_reconciliado_requiere_ancla_check CHECK (
        estado_inventario_5a = 'PENDIENTE'
        OR (unidad_base_familia IS NOT NULL AND reconciliacion_actual_id IS NOT NULL)
    );

-- Punto de corte auditable: no es saldo adicional ni movimiento de inventario.
CREATE TABLE public.inventario_reconciliacion (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    insumo_id bigint NOT NULL REFERENCES public.insumo(id),
    request_id uuid NOT NULL,
    saldo_observado numeric(19,6) NOT NULL,
    suma_movimientos_conocidos numeric(19,6) NOT NULL,
    delta_no_explicado numeric(19,6) NOT NULL,
    corte_en timestamptz NOT NULL,
    version_calculo varchar(50) NOT NULL,
    clasificacion varchar(50) NOT NULL,
    creado_en timestamptz NOT NULL DEFAULT now(),
    creado_por_usuario_id bigint REFERENCES public.usuario(id),
    revisado_en timestamptz,
    revisado_por_usuario_id bigint REFERENCES public.usuario(id),
    procedencia text,
    evidencia text,
    CONSTRAINT inventario_reconciliacion_saldo_check CHECK (saldo_observado >= 0),
    CONSTRAINT inventario_reconciliacion_delta_check CHECK (
        delta_no_explicado = saldo_observado - suma_movimientos_conocidos
    ),
    CONSTRAINT inventario_reconciliacion_version_check CHECK (length(btrim(version_calculo)) > 0),
    CONSTRAINT inventario_reconciliacion_clasificacion_check CHECK (length(btrim(clasificacion)) > 0),
    CONSTRAINT inventario_reconciliacion_revision_check CHECK (
        (revisado_en IS NULL AND revisado_por_usuario_id IS NULL)
        OR (revisado_en IS NOT NULL AND revisado_por_usuario_id IS NOT NULL)
    ),
    CONSTRAINT inventario_reconciliacion_request_unique UNIQUE (request_id),
    CONSTRAINT inventario_reconciliacion_corte_unique UNIQUE (insumo_id, corte_en, version_calculo),
    CONSTRAINT inventario_reconciliacion_insumo_id_unique UNIQUE (insumo_id, id)
);

-- La ancla seleccionada debe pertenecer al mismo insumo.
ALTER TABLE public.insumo
    ADD CONSTRAINT fk_insumo_reconciliacion_actual
    FOREIGN KEY (id, reconciliacion_actual_id)
    REFERENCES public.inventario_reconciliacion(insumo_id, id);

CREATE INDEX idx_insumo_reconciliacion_actual
    ON public.insumo(reconciliacion_actual_id)
    WHERE reconciliacion_actual_id IS NOT NULL;

-- CHECK no puede verificar otra tabla. El bloqueo de la ancla coordina una
-- promoción concurrente con cambios posteriores a su revisión.
CREATE FUNCTION public.validar_ancla_inventario_5a()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.estado_inventario_5a <> 'PENDIENTE' THEN
        PERFORM 1 FROM public.inventario_reconciliacion
        WHERE id = NEW.reconciliacion_actual_id AND insumo_id = NEW.id
          AND revisado_en IS NOT NULL AND revisado_por_usuario_id IS NOT NULL
        FOR SHARE;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'RECONCILIADO/ACTIVO_5A requiere ancla revisada del mismo insumo'
                USING ERRCODE = '23514';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER validar_ancla_inventario_5a
    BEFORE INSERT OR UPDATE OF estado_inventario_5a, reconciliacion_actual_id
    ON public.insumo FOR EACH ROW
    EXECUTE FUNCTION public.validar_ancla_inventario_5a();

-- Una revisión ya usada tampoco puede retirarse después de la promoción.
CREATE FUNCTION public.validar_revision_ancla_inventario_5a()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.revisado_en IS NULL THEN
        PERFORM 1 FROM public.insumo
        WHERE reconciliacion_actual_id = NEW.id
          AND estado_inventario_5a <> 'PENDIENTE'
        FOR SHARE;
        IF FOUND THEN
            RAISE EXCEPTION 'No se puede retirar la revisión de un ancla activa'
                USING ERRCODE = '23514';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER validar_revision_ancla_inventario_5a
    BEFORE UPDATE OF revisado_en, revisado_por_usuario_id
    ON public.inventario_reconciliacion FOR EACH ROW
    EXECUTE FUNCTION public.validar_revision_ancla_inventario_5a();
