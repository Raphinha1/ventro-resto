-- 5B.4a: compensaciones nuevas; jamás modifica recepción/ENTRADA original.
CREATE TABLE public.inventory_receipt_reversal (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_id bigint NOT NULL UNIQUE REFERENCES public.inventory_receipt(id),
    request_id uuid NOT NULL UNIQUE,
    command_fingerprint varchar(64) NOT NULL CHECK (command_fingerprint ~ '^[0-9a-f]{64}$'),
    fingerprint_version varchar(50) NOT NULL CHECK (length(btrim(fingerprint_version)) > 0),
    actor_usuario_id bigint NOT NULL REFERENCES public.usuario(id),
    motivo varchar(1000) NOT NULL CHECK (length(btrim(motivo)) > 0),
    registrado_en timestamptz NOT NULL DEFAULT clock_timestamp(),
    estado varchar(10) NOT NULL DEFAULT 'CONFIRMADO' CHECK (estado='CONFIRMADO'),
    sealed boolean NOT NULL DEFAULT false
);
CREATE TABLE public.inventory_receipt_reversal_line (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reversal_id bigint NOT NULL REFERENCES public.inventory_receipt_reversal(id),
    original_receipt_line_id bigint NOT NULL REFERENCES public.inventory_receipt_line(id),
    line_no integer NOT NULL CHECK (line_no > 0),
    insumo_id bigint NOT NULL REFERENCES public.insumo(id),
    familia varchar(8) NOT NULL,
    unidad_base_codigo varchar(8) NOT NULL,
    cantidad_base_compensada public.inventory_5b_quantity NOT NULL,
    operation_id uuid NOT NULL UNIQUE,
    CONSTRAINT reversal_line_number_unique UNIQUE (reversal_id,line_no),
    CONSTRAINT reversal_original_line_unique UNIQUE (reversal_id,original_receipt_line_id),
    CONSTRAINT reversal_unit_check CHECK (
        (familia='MASS' AND unidad_base_codigo='g') OR
        (familia='VOLUME' AND unidad_base_codigo='ml') OR
        (familia='COUNT' AND unidad_base_codigo='unidad'))
);
CREATE INDEX idx_reversal_line_original ON public.inventory_receipt_reversal_line(original_receipt_line_id);
CREATE INDEX idx_reversal_line_insumo ON public.inventory_receipt_reversal_line(insumo_id);

CREATE FUNCTION public.proteger_receipt_reversal() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP='INSERT' THEN NEW.sealed := false; RETURN NEW; END IF;
    IF TG_OP='UPDATE' THEN
        IF NOT OLD.sealed AND NEW.sealed AND pg_trigger_depth()>1
            AND (to_jsonb(NEW)-'sealed') IS NOT DISTINCT FROM (to_jsonb(OLD)-'sealed') THEN
            RETURN NEW;
        END IF;
    END IF;
    RAISE EXCEPTION 'Reverso confirmado inmutable' USING ERRCODE='23514';
END;
$$;
CREATE TRIGGER reversal_immutable BEFORE INSERT OR UPDATE OR DELETE ON public.inventory_receipt_reversal
    FOR EACH ROW EXECUTE FUNCTION public.proteger_receipt_reversal();

CREATE FUNCTION public.validar_receipt_reversal_line() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE original_receipt bigint;
BEGIN
    IF TG_OP <> 'INSERT' THEN
        RAISE EXCEPTION 'Línea de reverso confirmada inmutable' USING ERRCODE='23514';
    END IF;
    SELECT receipt_id INTO original_receipt FROM public.inventory_receipt_reversal
        WHERE id=NEW.reversal_id AND NOT sealed FOR SHARE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Las líneas deben crearse junto al reverso' USING ERRCODE='23514';
    END IF;
    PERFORM 1 FROM public.inventory_receipt_line l WHERE l.id=NEW.original_receipt_line_id
        AND l.receipt_id=original_receipt AND l.line_no=NEW.line_no AND l.insumo_id=NEW.insumo_id
        AND l.familia=NEW.familia AND l.unidad_base_codigo=NEW.unidad_base_codigo
        AND l.cantidad_base_efectiva=NEW.cantidad_base_compensada;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Reverso requiere pertenencia y snapshot original exactos' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER reversal_line_guard BEFORE INSERT OR UPDATE OR DELETE ON public.inventory_receipt_reversal_line
    FOR EACH ROW EXECUTE FUNCTION public.validar_receipt_reversal_line();

-- Cabecera antes de líneas y movimientos; cobertura/causas se validan al commit.
CREATE FUNCTION public.validar_receipt_reversal_completo() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM public.inventory_receipt r WHERE r.id=NEW.receipt_id AND r.sealed)
        OR NOT EXISTS (SELECT 1 FROM public.inventory_receipt_line WHERE receipt_id=NEW.receipt_id)
        OR EXISTS (
            SELECT 1 FROM public.inventory_receipt_line o
            LEFT JOIN public.inventory_receipt_reversal_line l
                ON l.original_receipt_line_id=o.id AND l.reversal_id=NEW.id
            LEFT JOIN public.inventory_receipt r ON r.id=o.receipt_id
            LEFT JOIN public.movimiento_inventario entrada ON entrada.operation_id=o.operation_id
            LEFT JOIN public.movimiento_inventario salida ON salida.operation_id=l.operation_id
            WHERE o.receipt_id=NEW.receipt_id AND (
                l.id IS NULL OR entrada.id IS NULL OR salida.id IS NULL
                OR ROW(entrada.insumo_id,entrada.usuario_id,entrada.tipo_movimiento,entrada.cantidad,
                       entrada.causal_origin,entrada.causal_reference)
                   IS DISTINCT FROM ROW(o.insumo_id,r.actor_usuario_id,'ENTRADA'::varchar,o.cantidad_base_efectiva,
                       'RECEPCION_RAPIDA'::varchar,('receipt:'||r.id||'/line:'||o.line_no)::varchar)
                OR ROW(salida.insumo_id,salida.usuario_id,salida.tipo_movimiento,salida.cantidad,
                       salida.causal_origin,salida.causal_reference,salida.comentario)
                   IS DISTINCT FROM ROW(l.insumo_id,NEW.actor_usuario_id,'SALIDA'::varchar,l.cantidad_base_compensada,
                       'REVERSO_RECEPCION_RAPIDA'::varchar,
                       ('receipt:'||NEW.receipt_id||'/reversal:'||NEW.id||'/line:'||l.line_no)::varchar,NEW.motivo))) THEN
        RAISE EXCEPTION 'Reverso requiere cobertura y efectos causales completos' USING ERRCODE='23514';
    END IF;
    UPDATE public.inventory_receipt_reversal SET sealed=true WHERE id=NEW.id;
    RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER reversal_complete AFTER INSERT ON public.inventory_receipt_reversal
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION public.validar_receipt_reversal_completo();
