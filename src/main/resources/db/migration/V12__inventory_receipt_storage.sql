-- 5B.1: solo persistencia. No modifica saldos ni crea movimientos.
-- NUMERIC(p,s) redondea ANTES de CHECK/trigger. Dominios sobre numeric sin
-- typmod conservan el valor de entrada y exigen exactamente sus rangos/escala.
CREATE DOMAIN public.inventory_5b_quantity AS numeric
    CHECK (VALUE > 0 AND VALUE < 10000000000000 AND VALUE = trunc(VALUE, 6));
CREATE DOMAIN public.inventory_5b_factor AS numeric
    CHECK (VALUE > 0 AND VALUE < 1000000000000 AND VALUE = trunc(VALUE, 12));
CREATE DOMAIN public.inventory_5b_cost AS numeric
    CHECK (VALUE > 0 AND VALUE < 100000000000000000 AND VALUE = trunc(VALUE, 2));

CREATE TABLE public.inventory_purchase_presentation (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    insumo_id bigint NOT NULL REFERENCES public.insumo(id),
    nombre varchar(150) NOT NULL CHECK (length(btrim(nombre)) > 0),
    unidad_compra_codigo varchar(50) NOT NULL CHECK (length(btrim(unidad_compra_codigo)) > 0),
    modo varchar(8) NOT NULL CHECK (modo IN ('FIJA', 'VARIABLE')),
    familia varchar(8) NOT NULL,
    unidad_base_codigo varchar(8) NOT NULL,
    factor_base public.inventory_5b_factor,
    estado varchar(8) NOT NULL DEFAULT 'ACTIVA' CHECK (estado IN ('ACTIVA', 'INACTIVA')),
    creado_por_usuario_id bigint NOT NULL REFERENCES public.usuario(id),
    creado_en timestamptz NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT presentation_unit_check CHECK (
        (familia='MASS' AND unidad_base_codigo='g') OR
        (familia='VOLUME' AND unidad_base_codigo='ml') OR
        (familia='COUNT' AND unidad_base_codigo='unidad')),
    CONSTRAINT presentation_mode_check CHECK (
        (modo='FIJA' AND factor_base IS NOT NULL) OR
        (modo='VARIABLE' AND factor_base IS NULL)),
    CONSTRAINT presentation_ingredient_unique UNIQUE (id, insumo_id)
);
CREATE INDEX idx_purchase_presentation_insumo ON public.inventory_purchase_presentation(insumo_id);

CREATE TABLE public.inventory_receipt (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id uuid NOT NULL UNIQUE,
    command_fingerprint varchar(64) NOT NULL CHECK (command_fingerprint ~ '^[0-9a-f]{64}$'),
    fingerprint_version varchar(50) NOT NULL CHECK (length(btrim(fingerprint_version)) > 0),
    estado varchar(10) NOT NULL DEFAULT 'CONFIRMADA' CHECK (estado='CONFIRMADA'),
    moneda varchar(3) NOT NULL CHECK (moneda ~ '^[A-Z]{3}$'),
    actor_usuario_id bigint NOT NULL REFERENCES public.usuario(id),
    registrado_en timestamptz NOT NULL DEFAULT clock_timestamp(),
    proveedor_id bigint REFERENCES public.proveedor(id),
    documento_externo varchar(200) CHECK (documento_externo IS NULL OR length(btrim(documento_externo)) > 0),
    -- El trigger diferido sella el agregado antes del commit, también tras restore.
    sealed boolean NOT NULL DEFAULT false
);

CREATE TABLE public.inventory_receipt_line (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_id bigint NOT NULL REFERENCES public.inventory_receipt(id),
    line_no integer NOT NULL CHECK (line_no > 0),
    insumo_id bigint NOT NULL REFERENCES public.insumo(id),
    presentation_id bigint NOT NULL,
    cantidad_comprada public.inventory_5b_quantity NOT NULL,
    cantidad_base_recibida public.inventory_5b_quantity,
    cantidad_base_efectiva public.inventory_5b_quantity NOT NULL,
    costo_total_real public.inventory_5b_cost NOT NULL,
    presentation_nombre varchar(150) NOT NULL CHECK (length(btrim(presentation_nombre)) > 0),
    unidad_compra_codigo varchar(50) NOT NULL CHECK (length(btrim(unidad_compra_codigo)) > 0),
    modo varchar(8) NOT NULL CHECK (modo IN ('FIJA', 'VARIABLE')),
    familia varchar(8) NOT NULL,
    unidad_base_codigo varchar(8) NOT NULL,
    factor_base public.inventory_5b_factor,
    calculation_version varchar(50) NOT NULL CHECK (length(btrim(calculation_version)) > 0),
    operation_id uuid NOT NULL UNIQUE,
    CONSTRAINT receipt_line_number_unique UNIQUE (receipt_id, line_no),
    CONSTRAINT receipt_line_presentation_fk FOREIGN KEY (presentation_id, insumo_id)
        REFERENCES public.inventory_purchase_presentation(id, insumo_id),
    CONSTRAINT receipt_line_unit_check CHECK (
        (familia='MASS' AND unidad_base_codigo='g') OR
        (familia='VOLUME' AND unidad_base_codigo='ml') OR
        (familia='COUNT' AND unidad_base_codigo='unidad')),
    CONSTRAINT receipt_line_conversion_check CHECK (
        (modo='FIJA' AND factor_base IS NOT NULL AND cantidad_base_recibida IS NULL
            AND cantidad_base_efectiva = cantidad_comprada * factor_base) OR
        (modo='VARIABLE' AND factor_base IS NULL AND cantidad_base_recibida IS NOT NULL
            AND cantidad_base_efectiva = cantidad_base_recibida))
);
CREATE INDEX idx_receipt_line_insumo ON public.inventory_receipt_line(insumo_id);
CREATE INDEX idx_receipt_line_presentation ON public.inventory_receipt_line(presentation_id);

-- La identidad de conversión no se edita: otra regla requiere otro ID.
CREATE FUNCTION public.proteger_purchase_presentation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP='UPDATE' THEN
        IF ROW(NEW.id,NEW.insumo_id,NEW.modo,NEW.familia,NEW.unidad_base_codigo,NEW.factor_base,NEW.unidad_compra_codigo,NEW.creado_por_usuario_id,NEW.creado_en)
            IS DISTINCT FROM
           ROW(OLD.id,OLD.insumo_id,OLD.modo,OLD.familia,OLD.unidad_base_codigo,OLD.factor_base,OLD.unidad_compra_codigo,OLD.creado_por_usuario_id,OLD.creado_en) THEN
            RAISE EXCEPTION 'Cambiar regla requiere una nueva presentación' USING ERRCODE='23514';
        END IF;
    ELSE
        PERFORM 1 FROM public.insumo WHERE id=NEW.insumo_id AND estado_inventario_5a='ACTIVO_5A'
            AND unidad_base_familia=NEW.familia AND unidad_base_codigo=NEW.unidad_base_codigo FOR SHARE;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'Presentación requiere insumo ACTIVO_5A y unidad coincidente' USING ERRCODE='23514';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER purchase_presentation_guard BEFORE INSERT OR UPDATE ON public.inventory_purchase_presentation
    FOR EACH ROW EXECUTE FUNCTION public.proteger_purchase_presentation();

CREATE FUNCTION public.proteger_inventory_receipt() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP='INSERT' THEN
        NEW.sealed := false;
        RETURN NEW;
    END IF;
    -- Único UPDATE interno: el trigger de restricción sella sin cambiar el hecho.
    IF TG_OP='UPDATE' THEN
        IF NOT OLD.sealed AND NEW.sealed AND pg_trigger_depth() > 1
            AND (to_jsonb(NEW)-'sealed') IS NOT DISTINCT FROM (to_jsonb(OLD)-'sealed') THEN
            RETURN NEW;
        END IF;
    END IF;
    RAISE EXCEPTION 'Recepción confirmada inmutable' USING ERRCODE='23514';
END;
$$;
CREATE TRIGGER receipt_immutable BEFORE INSERT OR UPDATE OR DELETE ON public.inventory_receipt
    FOR EACH ROW EXECUTE FUNCTION public.proteger_inventory_receipt();

CREATE FUNCTION public.validar_inventory_receipt_line() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE presentation public.inventory_purchase_presentation%ROWTYPE;
BEGIN
    IF TG_OP <> 'INSERT' THEN
        RAISE EXCEPTION 'Línea de recepción confirmada inmutable' USING ERRCODE='23514';
    END IF;
    PERFORM 1 FROM public.inventory_receipt WHERE id=NEW.receipt_id AND NOT sealed FOR SHARE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Las líneas deben crearse junto a la recepción' USING ERRCODE='23514';
    END IF;
    SELECT * INTO presentation FROM public.inventory_purchase_presentation
        WHERE id=NEW.presentation_id FOR SHARE;
    IF NOT FOUND OR presentation.estado <> 'ACTIVA' OR
       ROW(NEW.insumo_id,NEW.presentation_nombre,NEW.unidad_compra_codigo,NEW.modo,NEW.familia,NEW.unidad_base_codigo,NEW.factor_base)
        IS DISTINCT FROM
       ROW(presentation.insumo_id,presentation.nombre,presentation.unidad_compra_codigo,presentation.modo,presentation.familia,presentation.unidad_base_codigo,presentation.factor_base) THEN
        RAISE EXCEPTION 'Snapshot requiere presentación ACTIVA y regla coincidente' USING ERRCODE='23514';
    END IF;
    PERFORM 1 FROM public.insumo WHERE id=NEW.insumo_id AND estado_inventario_5a='ACTIVO_5A'
        AND unidad_base_familia=NEW.familia AND unidad_base_codigo=NEW.unidad_base_codigo FOR SHARE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Línea requiere insumo ACTIVO_5A y unidad coincidente' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER receipt_line_guard BEFORE INSERT OR UPDATE OR DELETE ON public.inventory_receipt_line
    FOR EACH ROW EXECUTE FUNCTION public.validar_inventory_receipt_line();

-- Permite insertar cabecera antes de sus líneas, pero no confirmar una vacía.
CREATE FUNCTION public.validar_inventory_receipt_completa() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM public.inventory_receipt_line WHERE receipt_id=NEW.id) THEN
        RAISE EXCEPTION 'Recepción confirmada requiere al menos una línea' USING ERRCODE='23514';
    END IF;
    UPDATE public.inventory_receipt SET sealed=true WHERE id=NEW.id;
    RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER receipt_nonempty AFTER INSERT ON public.inventory_receipt
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION public.validar_inventory_receipt_completa();
